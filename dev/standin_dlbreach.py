"""
dev/standin_dlbreach.py — STAND-IN FOR TESTING. THIS IS NOT DLBREACH.
=====================================================================

A deliberately crude program that behaves like the DLBreach executable at
its interface, so the dashboard's run, scenario and Monte Carlo paths can
be exercised on machines without DLBreach (continuous integration, Linux,
macOS, a reviewer's laptop):

* it reads the case name from standard input, as DLBreach does;
* it reads ``<case>.txt`` from the working folder with the dashboard's own
  input reader;
* it writes ``<case>.out`` with the 13 columns DLBreach writes, in the
  same order (Wu 2016, "Inputs and Outputs of DLBreach").

The numbers it writes come from a toy weir-and-erosion rule chosen only to
give smooth, plausible-looking curves that respond to the inputs. They have
no physical standing, are not calibrated, and must never be reported,
compared with DLBreach or used for any engineering purpose. Every output
file starts with a banner saying so.

Usage (normally via dev/make_standin.py, which wraps it as an executable):

    echo mycase | python dev/standin_dlbreach.py        # in the case folder
"""

from __future__ import annotations

import math
import sys
from pathlib import Path

BANNER = ("STAND-IN OUTPUT - NOT DLBREACH - generated by dev/standin_dlbreach.py "
          "for software testing only. Do not use these numbers.")


def _repo_root() -> Path:
    here = Path(__file__).resolve().parent
    return here.parent if here.name == "dev" else here


def _storage_fn(p: dict):
    """Volume above the embankment base as a function of level, V(z)."""
    method = int(p.get("reservoir_method", 2))
    curve = [tuple(map(float, xy)) for xy in (p.get("res_curve") or [])]
    if method == 0 and len(curve) >= 2:
        zs = [c[0] for c in curve]
        vs = [c[1] for c in curve]

        def V(z):
            if z <= zs[0]:
                return vs[0]
            for i in range(1, len(zs)):
                if z <= zs[i]:
                    f = (z - zs[i - 1]) / max(zs[i] - zs[i - 1], 1e-9)
                    return vs[i - 1] + f * (vs[i] - vs[i - 1])
            slope = (vs[-1] - vs[-2]) / max(zs[-1] - zs[-2], 1e-9)
            return vs[-1] + slope * (z - zs[-1])
        return V
    if method == 1 and len(curve) >= 2:
        # area curve: integrate by trapezoids
        pts = sorted(curve)
        acc = [0.0]
        for i in range(1, len(pts)):
            acc.append(acc[-1] + 0.5 * (pts[i][1] + pts[i - 1][1])
                       * (pts[i][0] - pts[i - 1][0]))
        zs = [c[0] for c in pts]

        def V(z):
            if z <= zs[0]:
                return 0.0
            for i in range(1, len(zs)):
                if z <= zs[i]:
                    f = (z - zs[i - 1]) / max(zs[i] - zs[i - 1], 1e-9)
                    return acc[i - 1] + f * (acc[i] - acc[i - 1])
            return acc[-1] + pts[-1][1] * (z - zs[-1])
        return V
    H = float(p.get("res_H", 18.0)) or 1.0
    VH = float(p.get("res_VH", 5e6))
    if method == 2:
        m = max(float(p.get("res_AH", 5e5)) * H / max(VH, 1.0), 0.2)
    else:
        m = max(float(p.get("res_m", 2.0)), 0.2)
    return lambda z: VH * (max(z, 0.0) / H) ** m


def _level_from_volume(V, vol, lo, hi):
    for _ in range(60):
        mid = 0.5 * (lo + hi)
        if V(mid) < vol:
            lo = mid
        else:
            hi = mid
    return 0.5 * (lo + hi)


def simulate(p: dict) -> list[list[float]]:
    """Toy breach: weir outflow and an erosion rate that grows with head."""
    crest = float(p["emb_height"])
    hard = float(p.get("hard_bottom_elev", 0.0))
    if int(p.get("breach_mode", 1)) == 1:
        z = crest - float(p.get("pilot_depth", 0.2))
        b = max(float(p.get("pilot_width", 1.0)), 0.1)
    else:
        z = crest - float(p.get("pipe_depth", 5.0))
        b = max(float(p.get("pipe_width", 0.1)), 0.1)
    z = max(z, hard)
    s = float(p.get("side_slope_constant") or 1.0)           # V/H
    d50 = max(float(p.get("sed_d50", 0.001)), 1e-6)
    n = max(float(p.get("manning_n", 0.02)), 1e-3)
    por = float(p.get("sed_porosity", 0.35))
    k_erode = 6e-4 * (0.001 / d50) ** 0.5 * (0.02 / n) ** 0.5
    V = _storage_fn(p)
    wsl = float(p["wsl_up_initial"])
    vol = V(wsl)
    wd0 = float(p.get("wsl_down_initial", 0.01))
    W = float(p.get("ds_channel_width", 100.0))
    S = max(float(p.get("ds_channel_slope", 0.01)), 1e-5)
    nd = float(p.get("ds_channel_n", 0.03))
    t0 = float(p.get("sim_start", 0.0))
    t1 = min(float(p.get("sim_end", 43200.0)), t0 + 5 * 86400.0)
    dt, every = 5.0, 12                                       # 1-minute output
    rows, cum, step, t = [], 0.0, 0, t0
    while t <= t1 + 1e-9:
        h = max(wsl - z, 0.0)
        top = b + 2.0 * max(crest - z, 0.0) / s
        q = 1.7 * (b + 0.8 * h / s) * h ** 1.5 if h > 0 else 0.0
        q = min(q, vol / dt) if vol > 0 else 0.0
        hc = 2.0 / 3.0 * h
        area = b * hc + hc * hc / s
        wd = wd0 + ((q * nd) / (W * math.sqrt(S))) ** 0.6 if q > 0 else wd0
        qs = q * 0.015 * (1 - por)
        if step % every == 0:
            rows.append([t / 3600.0, q, 0.0, wsl, wd, z, b, top, area, s,
                         cum, qs, qs])
        dz = k_erode * h ** 1.5 * dt
        if z - dz < hard:
            dz = max(z - hard, 0.0)
        z -= dz
        b += 1.2 * dz / s + 2e-4 * q ** 0.5 * dt
        vol = max(vol - q * dt, 0.0)
        cum += q * dt
        wsl = _level_from_volume(V, vol, -50.0, crest + 50.0) if vol > 0 else hard
        t += dt
        step += 1
    return rows


def write_out(rows: list[list[float]], path: Path) -> None:
    with open(path, "w", encoding="ascii") as f:
        f.write(f" {BANNER}\n")
        f.write(" Time(hr) Qbreach Qspill WSLup WSLdn Zb Bbot Btop Abreach "
                "SideSlope CumVol QsUp QsDn\n")
        for r in rows:
            f.write(" " + " ".join(f"{v:14.6e}" for v in r) + "\n")


def main() -> int:
    sys.path.insert(0, str(_repo_root()))
    from dlbreach_io import DEFAULT_PARAMS, read_input_file

    print("STAND-IN, NOT DLBREACH. Enter case name:")
    case = (sys.stdin.readline() or "").strip()
    src = Path.cwd() / f"{case}.txt"
    if not case or not src.is_file():
        print(f"Input file not found: {src}")
        return 1
    p = dict(DEFAULT_PARAMS)
    p.update(read_input_file(src.read_text(errors="replace")))
    write_out(simulate(p), Path.cwd() / f"{case}.out")
    print(f"Wrote {case}.out (stand-in output, not DLBreach)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
